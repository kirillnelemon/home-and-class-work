    def validate_and_convert(
        self,
    ):  # Метод проверки введенных пользователем данных
        try:  # Открываем блок перехвата возможных ошибок
            h = int(
                self.hours_entry.get() or 0
            )  # Считываем часы, преобразуем в int (если пусто, берем 0)
            m = int(
                self.mins_entry.get() or 0
            )  # Считываем минуты, преобразуем в int (если пусто, берем 0)
            s = int(
                self.secs_entry.get() or 0
            )  # Считываем секунды, преобразуем в int (если пусто, берем 0)

            if (
                h < 0 or m < 0 or s < 0
            ):  # Проверяем, нет ли среди введенных чисел отрицательных
                raise ValueError  # Если нашли минус, принудительно вызываем ошибку

            return (
                h * 3600 + m * 60 + s
            )  # Переводим всё время в секунды и возвращаем сумму
        except ValueError:  # Если пользователь ввел буквы, знаки или отрицательные числа
            messagebox.showerror(  # Показываем всплывающее критическое окно
                "Ошибка", "Введите корректные целые положительные числа!"
            )  # Текст сообщения об ошибке
            return None  # Возвращаем пустоту (сигнал о неудачной валидации)

    def update_countdown(self):  # Рекурсивный метод отсчета времени каждую секунду
        if (
            not self.is_running
        ):  # Если флаг работы выключен (нажали паузу или сброс)
            return  # Немедленно прерываем выполнение метода

